/// A solution to a polynomial system (numerical approximation).
#[derive(Debug, Clone)]
pub struct RealSolution {
    /// Variable values, one per variable in the original system.
    pub values: Vec<f64>,
    /// Algebraic multiplicity of this solution.
    pub multiplicity: usize,
}

/// Result of solving a zero-dimensional polynomial system.
#[derive(Debug, Clone)]
pub struct ZeroDimSolutions {
    /// The real solutions found.
    pub solutions: Vec<RealSolution>,
    /// The dimension of the quotient ring k[x₁,...,xₙ]/I
    /// (number of solutions counted with multiplicity over ℂ).
    pub vector_space_dimension: usize,
}

/// Result of solving a polynomial system.
#[derive(Debug, Clone)]
pub enum PolynomialSystemSolution {
    /// Finite number of real solutions.
    ZeroDimensional(ZeroDimSolutions),
    /// Infinite solution set; the Gröbner basis in Lex order.
    PositiveDimensional(GroebnerBasis<RationalDomain, Lex>),
    /// No solutions (the ideal is ⟨1⟩).
    Empty,
}

/// Check whether an ideal is zero-dimensional.
///
/// An ideal is zero-dimensional iff for every variable $x_i$, some leading
/// monomial in the GB is a pure power $x_i^N$. Equivalently, the staircase
/// (standard monomials) is finite.
///
/// # Example
///
/// ```
/// use ocas_domain::{RationalDomain, Rational};
/// use ocas_poly::sparse::Lex;
/// use ocas_poly::{Algorithm, GroebnerBasis, SparseMultivariatePolynomial, groebner_basis};
/// use ocas_poly::ideal::is_zero_dimensional;
///
/// let d = RationalDomain;
/// // x² - 1, y - x → zero-dimensional
/// let f1 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![2, 0], Rational::new(1, 1)),
///     (vec![0, 0], Rational::new(-1, 1)),
/// ]);
/// let f2 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![0, 1], Rational::new(1, 1)),
///     (vec![1, 0], Rational::new(-1, 1)),
/// ]);
/// let gb = groebner_basis(&[f1, f2], Algorithm::F4);
/// assert!(is_zero_dimensional(&gb));
/// ```
pub fn is_zero_dimensional(gb: &GroebnerBasis<RationalDomain, Lex>) -> bool {
    let n_vars = match gb.basis.first() {
        Some(p) => p.n_vars(),
        None => return false, // empty ideal is not zero-dimensional
    };

    // For each variable, check that some leading monomial is a pure power.
    for var in 0..n_vars {
        let has_pure_power = gb.basis.iter().any(|p| {
            match p.leading_monomial() {
                Some(lm) => {
                    lm.iter()
                        .enumerate()
                        .all(|(i, &e)| if i == var { e > 0 } else { e == 0 })
                }
                None => false,
            }
        });
        if !has_pure_power {
            return false;
        }
    }
    true
}

/// Extract a univariate polynomial from a multivariate one, treating it
/// as a polynomial in `var_index` with rational coefficients.
/// All other variables must have exponent 0.
fn extract_univariate(
    poly: &SparseMultivariatePolynomial<RationalDomain, Lex>,
    var_index: usize,
) -> crate::dense::DenseUnivariatePolynomial<RationalDomain> {
    let d = RationalDomain;
    let deg = poly.degree_in(var_index);
    let mut coeffs = vec![ocas_domain::Rational::new(0, 1); deg + 1];
    for (exp, coeff) in poly.terms_ref() {
        let power = exp.get(var_index).copied().unwrap_or(0);
        coeffs[power] = coeffs[power].clone() + coeff.clone();
    }
    crate::dense::DenseUnivariatePolynomial::from_coeffs(d, coeffs)
}

/// Solve for one variable given a polynomial and values for higher-index
/// variables already substituted. Returns the real roots as f64.
fn solve_univariate_f64(
    poly: &SparseMultivariatePolynomial<RationalDomain, Lex>,
    var_index: usize,
    substituted_values: &[f64], // values for variables > var_index
) -> Vec<f64> {
    // Build the univariate polynomial in var_index by substituting the
    // already-known values for higher-index variables.
    let d = RationalDomain;
    let deg = poly.degree_in(var_index);
    let mut coeffs_f64 = vec![0.0f64; deg + 1];

    for (exp, coeff) in poly.terms_ref() {
        // Check that variables > var_index have exponent 0 or are substituted.
        let mut coeff_f = format!("{}", coeff).parse::<f64>().unwrap_or(0.0);
        for (i, &e) in exp.iter().enumerate() {
            if i > var_index && e > 0 {
                // Variable i has been substituted.
                let sub_idx = i - var_index - 1;
                if sub_idx < substituted_values.len() {
                    coeff_f *= substituted_values[sub_idx].powi(e as i32);
                }
            }
        }
        let power = exp.get(var_index).copied().unwrap_or(0);
        coeffs_f64[power] += coeff_f;
    }

    // Convert to Rational coefficients and use Sturm-based root isolation.
    let rational_coeffs: Vec<ocas_domain::Rational> = coeffs_f64
        .iter()
        .map(|&c| rational_approx(c))
        .collect();
    let unipoly =
        crate::dense::DenseUnivariatePolynomial::from_coeffs(d, rational_coeffs);
    let intervals = unipoly.isolate_real_roots();
    intervals
        .iter()
        .map(|iv| {
            let refined = unipoly.refine_root(iv, 1e-14);
            (refined.low + refined.high) / 2.0
        })
        .collect()
}

/// Approximate f64 to Rational using continued fractions.
fn rational_approx(x: f64) -> ocas_domain::Rational {
    if x == 0.0 {
        return ocas_domain::Rational::new(0, 1);
    }
    let sign: i64 = if x < 0.0 { -1 } else { 1 };
    let x_abs = x.abs();
    let mut a = x_abs.floor() as i64;
    let mut frac = x_abs - a as f64;
    let mut prev_num = 1i64;
    let mut prev_den = 0i64;
    let mut num = a;
    let mut den = 1i64;

    for _ in 0..50 {
        if frac.abs() < 1e-12 {
            break;
        }
        let r = 1.0 / frac;
        a = r.floor() as i64;
        frac = r - a as f64;
        let new_num = a * num + prev_num;
        let new_den = a * den + prev_den;
        prev_num = num;
        prev_den = den;
        num = new_num;
        den = new_den;
        if den > 1_000_000 {
            break;
        }
    }
    ocas_domain::Rational::new(sign * num, den)
}

/// Solve a zero-dimensional system using triangular decomposition.
///
/// Converts the GB to Lex order, extracts univariate polynomials for each
/// variable, and solves by back-substitution.
///
/// # Example
///
/// ```
/// use ocas_domain::{RationalDomain, Rational};
/// use ocas_poly::sparse::Lex;
/// use ocas_poly::{Algorithm, SparseMultivariatePolynomial, groebner_basis};
/// use ocas_poly::ideal::{solve_polynomial_system, PolynomialSystemSolution};
///
/// let d = RationalDomain;
/// // x² + y² - 1, x - y → solutions at (±1/√2, ±1/√2)
/// let f1 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![2, 0], Rational::new(1, 1)),
///     (vec![0, 2], Rational::new(1, 1)),
///     (vec![0, 0], Rational::new(-1, 1)),
/// ]);
/// let f2 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![1, 0], Rational::new(1, 1)),
///     (vec![0, 1], Rational::new(-1, 1)),
/// ]);
/// let sol = solve_polynomial_system(&[f1, f2], Algorithm::Auto);
/// match sol {
///     PolynomialSystemSolution::ZeroDimensional(z) => {
///         assert_eq!(z.solutions.len(), 2);
///     }
///     _ => panic!("expected zero-dimensional"),
/// }
/// ```
pub fn solve_polynomial_system(
    equations: &[SparseMultivariatePolynomial<RationalDomain, Lex>],
    algo: Algorithm,
) -> PolynomialSystemSolution {
    if equations.is_empty() {
        return PolynomialSystemSolution::PositiveDimensional(GroebnerBasis { basis: vec![] });
    }

    let gb = groebner_basis(equations, algo);

    // Check for empty variety: GB = {1}.
    if gb.basis.len() == 1
        && gb.basis[0].terms_ref().len() == 1
        && gb.basis[0]
            .leading_monomial()
            .map(|lm| lm.iter().all(|&e| e == 0))
            .unwrap_or(false)
    {
        return PolynomialSystemSolution::Empty;
    }

    // Convert to Lex for triangular decomposition.
    let gb_lex: GroebnerBasis<RationalDomain, Lex> = gb;
    // If already in Lex, use directly; otherwise convert.
    // (Our GB functions preserve the input order, so check.)

    if !is_zero_dimensional(&gb_lex) {
        return PolynomialSystemSolution::PositiveDimensional(gb_lex);
    }

    let solutions = solve_triangular(&gb_lex);
    // The vector-space dimension equals the number of solutions over ℂ,
    // which we approximate as the product of univariate polynomial degrees
    // in the Lex GB.
    let dim = compute_vector_space_dim(&gb_lex).unwrap_or(solutions.len());

    PolynomialSystemSolution::ZeroDimensional(ZeroDimSolutions {
        solutions,
        vector_space_dimension: dim,
    })
}

/// Compute the vector-space dimension of k[x₁,...,xₙ]/I for a zero-dimensional
/// ideal. This is the product of the degrees of the univariate polynomials
/// for each variable in the Lex GB.
fn compute_vector_space_dim(gb: &GroebnerBasis<RationalDomain, Lex>) -> Option<usize> {
    let n_vars = gb.basis.first()?.n_vars();
    let mut dim = 1usize;
    for var in 0..n_vars {
        let max_deg = gb
            .basis
            .iter()
            .filter(|p| {
                p.terms_ref()
                    .keys()
                    .all(|e| e.iter().enumerate().all(|(i, &v)| i == var || v == 0))
            })
            .map(|p| p.degree_in(var))
            .max()
            .unwrap_or(1);
        dim = dim.checked_mul(max_deg)?;
    }
    Some(dim)
}

/// Solve a triangular Lex GB by back-substitution.
/// Starts from the last variable (smallest in Lex) and works backwards.
fn solve_triangular(
    gb: &GroebnerBasis<RationalDomain, Lex>,
) -> Vec<RealSolution> {
    let n_vars = match gb.basis.first() {
        Some(p) => p.n_vars(),
        None => return vec![],
    };

    // Start from the last variable and work backwards.
    let raw = solve_recursive(gb, n_vars - 1, &[]);
    // Reverse the values since we built them last-var-first.
    raw.into_iter()
        .map(|mut s| {
            s.values.reverse();
            s
        })
        .collect()
}

/// Recursive back-substitution solver.
/// Solves variable `var_index` given values for variables `var_index+1..n_vars-1`.
/// `higher_values[0]` = value for variable `var_index+1`, etc.
fn solve_recursive(
    gb: &GroebnerBasis<RationalDomain, Lex>,
    var_index: usize,
    higher_values: &[f64],
) -> Vec<RealSolution> {
    // First, try to find a polynomial that's purely univariate in var_index
    // (no higher variables involved).
    let univariate_poly = gb.basis.iter().find(|p| {
        p.degree_in(var_index) > 0
            && p.terms_ref().keys().all(|e| {
                e.iter()
                    .enumerate()
                    .all(|(i, &v)| i <= var_index || v == 0)
            })
    });

    let roots = if let Some(poly) = univariate_poly {
        // Pure univariate: extract and solve directly.
        let unipoly = extract_univariate(poly, var_index);
        let intervals = unipoly.isolate_real_roots();
        let r: Vec<f64> = intervals
            .iter()
            .map(|iv| {
                let refined = unipoly.refine_root(iv, 1e-14);
                (refined.low + refined.high) / 2.0
            })
            .collect();
        r
    } else {
        // Find a polynomial involving var_index and possibly higher variables.
        // Substitute known values for higher variables to get univariate.
        let poly = gb.basis.iter().find(|p| p.degree_in(var_index) > 0);
        let Some(poly) = poly else {
            return vec![];
        };
        solve_univariate_f64(poly, var_index, higher_values)
    };

    if var_index == 0 {
        // Base case: last variable to solve.
        roots
            .into_iter()
            .map(|v| RealSolution {
                values: vec![v],
                multiplicity: 1,
            })
            .collect()
    } else {
        // For each root, recurse to solve the next lower variable.
        let mut results = Vec::new();
        for root in &roots {
            let mut new_higher = Vec::with_capacity(higher_values.len() + 1);
            new_higher.push(*root);
            new_higher.extend_from_slice(higher_values);
            let sub_solutions = solve_recursive(gb, var_index - 1, &new_higher);
            for mut sol in sub_solutions {
                sol.values.push(*root);
                results.push(sol);
            }
        }
        results
    }
}

