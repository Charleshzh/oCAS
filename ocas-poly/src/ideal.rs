    #[test]
    fn solve_circle_line() {
        // x² + y² - 1, x - y → 2 solutions at (±1/√2, ±1/√2)
        let d = RationalDomain;
        let f1 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
            (vec![2, 0], r(1, 1)),
            (vec![0, 2], r(1, 1)),
            (vec![0, 0], r(-1, 1)),
        ]);
        let f2 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
            (vec![1, 0], r(1, 1)),
            (vec![0, 1], r(-1, 1)),
        ]);
        let sol = solve_polynomial_system(&[f1, f2], Algorithm::Auto);
        match sol {
            PolynomialSystemSolution::ZeroDimensional(z) => {
                assert_eq!(z.solutions.len(), 2);
                // Check that solutions are approximately (±0.707, ±0.707)
                for s in &z.solutions {
                    let x_val = s.values[0];
                    let y_val = s.values[1];
                    assert!((x_val - y_val).abs() < 1e-10, "x should equal y");
                    assert!(
                        (x_val * x_val + y_val * y_val - 1.0).abs() < 1e-10,
                        "x² + y² should be 1"
                    );
                }
            }
            _ => panic!("expected zero-dimensional"),
        }
    }

