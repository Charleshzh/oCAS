//! Ideal operations for polynomial rings.
//!
//! Provides fundamental ideal arithmetic based on Gröbner bases:
//! membership testing, sum, product, quotient, saturation, and intersection.
//!
//! All operations work over [`Lex`] ordering for consistency with
//! elimination-based computations.
//!
//! # References
//!
//! - Cox, Little, O'Shea: *Ideals, Varieties, and Algorithms*
//! - Adams & Loustaunau: *An Introduction to Gröbner Bases*

use ocas_domain::Domain;
use ocas_domain::{Rational, RationalDomain};

use crate::groebner::{Algorithm, GroebnerBasis, groebner_basis};
use crate::sparse::{Lex, SparseMultivariatePolynomial};

/// Test whether `f` belongs to the ideal generated by `generators`.
///
/// Computes a Gröbner basis of the ideal and reduces `f` against it.
/// `f ∈ I` iff the remainder is zero.
///
/// # Example
///
/// ```
/// use ocas_domain::{RationalDomain, Rational};
/// use ocas_poly::sparse::Lex;
/// use ocas_poly::ideal::ideal_contains;
/// use ocas_poly::{Algorithm, SparseMultivariatePolynomial};
///
/// let d = RationalDomain;
/// let x = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![1, 0], Rational::new(1, 1)),
/// ]);
/// let y = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![0, 1], Rational::new(1, 1)),
/// ]);
/// assert!(ideal_contains(&[x.clone(), y.clone()], &x, Algorithm::Auto));
/// // x ∉ ⟨y⟩
/// assert!(!ideal_contains(&[y], &x, Algorithm::Auto));
/// ```
pub fn ideal_contains<D: Domain + 'static>(
    generators: &[SparseMultivariatePolynomial<D, Lex>],
    f: &SparseMultivariatePolynomial<D, Lex>,
    algo: Algorithm,
) -> bool {
    if generators.is_empty() {
        return f.is_zero();
    }
    let gb = groebner_basis(generators, algo);
    let remainder = f.reduce(&gb.basis);
    remainder.is_zero()
}

/// Sum of two ideals: `I + J = ⟨f₁,…,fₘ, g₁,…,gₙ⟩`.
///
/// # Example
///
/// ```
/// use ocas_domain::{RationalDomain, Rational};
/// use ocas_poly::sparse::Lex;
/// use ocas_poly::ideal::ideal_sum;
/// use ocas_poly::{Algorithm, SparseMultivariatePolynomial};
///
/// let d = RationalDomain;
/// let x = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![1, 0], Rational::new(1, 1)),
/// ]);
/// let y = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![0, 1], Rational::new(1, 1)),
/// ]);
/// let gb = ideal_sum(&[x], &[y]);
/// // ⟨x⟩ + ⟨y⟩ = ⟨x, y⟩
/// assert!(gb.basis.len() >= 2);
/// ```
pub fn ideal_sum<D: Domain + 'static>(
    generators_a: &[SparseMultivariatePolynomial<D, Lex>],
    generators_b: &[SparseMultivariatePolynomial<D, Lex>],
) -> GroebnerBasis<D, Lex> {
    let mut combined = generators_a.to_vec();
    combined.extend(generators_b.iter().cloned());
    groebner_basis(&combined, Algorithm::Auto)
}

/// Product of two ideals: `I · J = ⟨fᵢ · gⱼ⟩`.
///
/// # Example
///
/// ```
/// use ocas_domain::{RationalDomain, Rational};
/// use ocas_poly::sparse::Lex;
/// use ocas_poly::ideal::ideal_product;
/// use ocas_poly::SparseMultivariatePolynomial;
///
/// let d = RationalDomain;
/// let x = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![1, 0], Rational::new(1, 1)),
/// ]);
/// let y = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![0, 1], Rational::new(1, 1)),
/// ]);
/// let gb = ideal_product(&[x], &[y]);
/// // ⟨x⟩ · ⟨y⟩ = ⟨xy⟩
/// assert_eq!(gb.basis.len(), 1);
/// ```
pub fn ideal_product<D: Domain + 'static>(
    generators_a: &[SparseMultivariatePolynomial<D, Lex>],
    generators_b: &[SparseMultivariatePolynomial<D, Lex>],
) -> GroebnerBasis<D, Lex> {
    let products: Vec<SparseMultivariatePolynomial<D, Lex>> = generators_a
        .iter()
        .flat_map(|f| generators_b.iter().map(move |g| f.mul(g)))
        .collect();
    groebner_basis(&products, Algorithm::Auto)
}

/// Ideal quotient: `I : J = {f : f · g ∈ I, ∀ g ∈ J}`.
///
/// Computed via the Rabinowitsch trick for each generator of J,
/// then intersecting the results.
///
/// For a single generator `g`: `I : g` is obtained by computing
/// `GB(I ∪ {1 - w·g})` in `k[x₁,…,xₙ, w]` and eliminating `w`.
///
/// # Example
///
/// ```
/// use ocas_domain::{RationalDomain, Rational};
/// use ocas_poly::sparse::Lex;
/// use ocas_poly::ideal::ideal_quotient;
/// use ocas_poly::SparseMultivariatePolynomial;
///
/// let d = RationalDomain;
/// // ⟨x², xy⟩ : ⟨x⟩ = ⟨x⟩
/// let f1 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![2, 0], Rational::new(1, 1)),
/// ]);
/// let f2 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![1, 1], Rational::new(1, 1)),
/// ]);
/// let g = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![1, 0], Rational::new(1, 1)),
/// ]);
/// let gb = ideal_quotient(&[f1, f2], &[g]);
/// // Result should generate the same ideal as ⟨x⟩
/// assert!(!gb.basis.is_empty());
/// ```
pub fn ideal_quotient<D: Domain + 'static>(
    generators_i: &[SparseMultivariatePolynomial<D, Lex>],
    generators_j: &[SparseMultivariatePolynomial<D, Lex>],
) -> GroebnerBasis<D, Lex> {
    if generators_i.is_empty() || generators_j.is_empty() {
        return GroebnerBasis { basis: vec![] };
    }

    // I : J = ∩_{g ∈ J} (I : g)
    let mut result: Option<Vec<SparseMultivariatePolynomial<D, Lex>>> = None;

    for g in generators_j {
        if g.is_zero() {
            continue;
        }
        let i_colon_g = quotient_single_generator(generators_i, g);

        if let Some(current) = result.take() {
            result = Some(intersect_generators(&current, &i_colon_g));
        } else {
            result = Some(i_colon_g);
        }
    }

    match result {
        None => GroebnerBasis { basis: vec![] },
        Some(gens) => {
            if gens.is_empty() {
                GroebnerBasis { basis: vec![] }
            } else {
                groebner_basis(&gens, Algorithm::Auto)
            }
        }
    }
}

/// Compute `I : g` for a single generator using the Rabinowitsch trick.
///
/// In the extended ring `k[x₁,…,xₙ, w]`, compute `GB(I' ∪ {1 - w·g'})`
/// and eliminate `w` (index 0) to get `I : g ⊂ k[x₁,…,xₙ]`.
fn quotient_single_generator<D: Domain + 'static>(
    generators_i: &[SparseMultivariatePolynomial<D, Lex>],
    g: &SparseMultivariatePolynomial<D, Lex>,
) -> Vec<SparseMultivariatePolynomial<D, Lex>> {
    let n_vars = g.n_vars();
    let domain = g.domain().clone();

    // Embed I into k[x₁,…,xₙ, w] (w is variable 0).
    let embedded: Vec<SparseMultivariatePolynomial<D, Lex>> = generators_i
        .iter()
        .map(|p| p.embed_new_main())
        .collect();

    // Embed g and compute 1 - w·g.
    let g_embedded = g.embed_new_main();
    let w = {
        let mut exp = smallvec::SmallVec::<[usize; 4]>::from_elem(0, n_vars + 1);
        exp[0] = 1;
        SparseMultivariatePolynomial::from_terms(domain.clone(), n_vars + 1, vec![
            (exp.to_vec(), domain.one()),
        ])
    };
    let wg = w.mul(&g_embedded);
    let one_minus_wg = {
        let one_exp = smallvec::SmallVec::<[usize; 4]>::from_elem(0, n_vars + 1);
        let one = SparseMultivariatePolynomial::from_terms(domain.clone(), n_vars + 1, vec![
            (one_exp.to_vec(), domain.one()),
        ]);
        one.sub(&wg)
    };

    let mut combined = embedded;
    combined.push(one_minus_wg);

    // Compute GB and eliminate w (variable 0), then strip w from result.
    let elim_gb = crate::groebner::eliminate(&combined, 1, Algorithm::Auto);
    elim_gb.basis.into_iter().map(|p| p.drop_variable(0)).collect()
}

/// Compute the intersection of two ideals given by their generators.
///
/// Uses the standard trick: `I ∩ J = ⟨t·fᵢ, (1-t)·gⱼ⟩ ∩ k[x₁,…,xₙ]`
/// where `t` is a new variable (index 0 after embedding).
fn intersect_generators<D: Domain + 'static>(
    generators_a: &[SparseMultivariatePolynomial<D, Lex>],
    generators_b: &[SparseMultivariatePolynomial<D, Lex>],
) -> Vec<SparseMultivariatePolynomial<D, Lex>> {
    let n_vars = generators_a
        .first()
        .or(generators_b.first())
        .map(|p| p.n_vars())
        .unwrap_or(0);
    let domain = generators_a
        .first()
        .or(generators_b.first())
        .map(|p| p.domain().clone())
        .unwrap_or_else(|| {
            // This case shouldn't happen in practice since callers check emptiness.
            unreachable!("intersect_generators called with empty inputs")
        });

    if generators_a.is_empty() || generators_b.is_empty() {
        return vec![];
    }

    // Embed into k[x₁,…,xₙ, t] (t is variable 0).
    let t = {
        let mut exp = smallvec::SmallVec::<[usize; 4]>::from_elem(0, n_vars + 1);
        exp[0] = 1;
        SparseMultivariatePolynomial::from_terms(domain.clone(), n_vars + 1, vec![
            (exp.to_vec(), domain.one()),
        ])
    };
    let one_minus_t = {
        let one_exp = smallvec::SmallVec::<[usize; 4]>::from_elem(0, n_vars + 1);
        let one = SparseMultivariatePolynomial::from_terms(domain.clone(), n_vars + 1, vec![
            (one_exp.to_vec(), domain.one()),
        ]);
        one.sub(&t)
    };

    let mut combined: Vec<SparseMultivariatePolynomial<D, Lex>> = Vec::new();

    // t · fᵢ
    for f in generators_a {
        let f_emb = f.embed_new_main();
        combined.push(t.mul(&f_emb));
    }
    // (1-t) · gⱼ
    for g in generators_b {
        let g_emb = g.embed_new_main();
        combined.push(one_minus_t.mul(&g_emb));
    }

    // Eliminate w (variable 0) and strip it from result polynomials.
    let elim_gb = crate::groebner::eliminate(&combined, 1, Algorithm::Auto);
    elim_gb.basis.into_iter().map(|p| p.drop_variable(0)).collect()
}

/// Ideal intersection: `I ∩ J`.
///
/// Uses the standard trick with an auxiliary variable `t`:
/// `I ∩ J = ⟨t·fᵢ, (1-t)·gⱼ⟩ ∩ k[x₁,…,xₙ]`.
///
/// # Example
///
/// ```
/// use ocas_domain::{RationalDomain, Rational};
/// use ocas_poly::sparse::Lex;
/// use ocas_poly::ideal::ideal_intersection;
/// use ocas_poly::SparseMultivariatePolynomial;
///
/// let d = RationalDomain;
/// let x = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![1, 0], Rational::new(1, 1)),
/// ]);
/// let y = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![0, 1], Rational::new(1, 1)),
/// ]);
/// let gb = ideal_intersection(&[x], &[y]);
/// // ⟨x⟩ ∩ ⟨y⟩ = ⟨xy⟩
/// assert_eq!(gb.basis.len(), 1);
/// ```
pub fn ideal_intersection<D: Domain + 'static>(
    generators_a: &[SparseMultivariatePolynomial<D, Lex>],
    generators_b: &[SparseMultivariatePolynomial<D, Lex>],
) -> GroebnerBasis<D, Lex> {
    if generators_a.is_empty() || generators_b.is_empty() {
        return GroebnerBasis { basis: vec![] };
    }
    let gens = intersect_generators(generators_a, generators_b);
    if gens.is_empty() {
        GroebnerBasis { basis: vec![] }
    } else {
        groebner_basis(&gens, Algorithm::Auto)
    }
}

/// Ideal saturation: `I : J^∞ = ⋃_k (I : Jᵏ)`.
///
/// Iteratively computes `I : J`, `(I : J) : J`, etc. until stable.
///
/// # Example
///
/// ```
/// use ocas_domain::{RationalDomain, Rational};
/// use ocas_poly::sparse::Lex;
/// use ocas_poly::ideal::ideal_saturate;
/// use ocas_poly::SparseMultivariatePolynomial;
///
/// let d = RationalDomain;
/// // ⟨x²y, xy²⟩ :⟨x⟩^∞ = ⟨y⟩
/// let f1 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![2, 1], Rational::new(1, 1)),
/// ]);
/// let f2 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![1, 2], Rational::new(1, 1)),
/// ]);
/// let g = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![1, 0], Rational::new(1, 1)),
/// ]);
/// let gb = ideal_saturate(&[f1, f2], &[g]);
/// assert!(!gb.basis.is_empty());
/// ```
pub fn ideal_saturate<D: Domain + 'static>(
    generators_i: &[SparseMultivariatePolynomial<D, Lex>],
    generators_j: &[SparseMultivariatePolynomial<D, Lex>],
) -> GroebnerBasis<D, Lex> {
    if generators_i.is_empty() {
        return GroebnerBasis { basis: vec![] };
    }
    if generators_j.is_empty() {
        return groebner_basis(generators_i, Algorithm::Auto);
    }

    let mut current_gens = generators_i.to_vec();
    let max_iter = 20;

    for _ in 0..max_iter {
        let current_gb = groebner_basis(&current_gens, Algorithm::Auto);
        let next = ideal_quotient(&current_gb.basis, generators_j);
        let next_gb = groebner_basis(&next.basis, Algorithm::Auto);

        // Check if stable: next_gb ⊂ current_gb and current_gb ⊂ next_gb.
        let all_in_current = next_gb
            .basis
            .iter()
            .all(|p| p.reduce(&current_gb.basis).is_zero());
        let all_in_next = current_gb
            .basis
            .iter()
            .all(|p| p.reduce(&next_gb.basis).is_zero());

        if all_in_current && all_in_next {
            return current_gb;
        }
        current_gens = next_gb.basis;
    }

    groebner_basis(&current_gens, Algorithm::Auto)
}

