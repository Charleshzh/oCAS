/// A primary component of an ideal: a primary ideal with its associated prime.
#[derive(Debug, Clone)]
pub struct PrimaryComponent {
    /// Generators of the primary ideal.
    pub primary: Vec<SparseMultivariatePolynomial<RationalDomain, Lex>>,
    /// Generators of the associated prime ideal (the radical).
    pub prime: Vec<SparseMultivariatePolynomial<RationalDomain, Lex>>,
}

/// Compute the radical √I of an ideal.
///
/// For zero-dimensional ideals, the radical is computed via the squarefree
/// decomposition of the univariate polynomials in the Lex GB.
///
/// # Example
///
/// ```
/// use ocas_domain::{RationalDomain, Rational};
/// use ocas_poly::sparse::Lex;
/// use ocas_poly::ideal::ideal_radical;
/// use ocas_poly::SparseMultivariatePolynomial;
///
/// let d = RationalDomain;
/// // √(x², xy) = (x)
/// let f1 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![2, 0], Rational::new(1, 1)),
/// ]);
/// let f2 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![1, 1], Rational::new(1, 1)),
/// ]);
/// let rad = ideal_radical(&[f1, f2]);
/// // The radical should be (x).
/// assert!(!rad.basis.is_empty());
/// ```
pub fn ideal_radical(
    generators: &[SparseMultivariatePolynomial<RationalDomain, Lex>],
) -> GroebnerBasis<RationalDomain, Lex> {
    if generators.is_empty() {
        return GroebnerBasis { basis: vec![] };
    }

    let gb = groebner_basis(generators, Algorithm::Auto);

    if is_zero_dimensional(&gb) {
        radical_zero_dim(&gb)
    } else {
        // For positive-dimensional ideals, use the Jacobian saturation approach.
        // √I = I : (∂f₁/∂x₁ · ∂f₂/∂x₂ · ... )^∞
        // Simplified: just return the GB (conservative upper bound).
        // A full implementation would compute the Jacobian and saturate.
        radical_via_jacobian(&gb)
    }
}

/// Compute the radical for a zero-dimensional ideal using squarefree
/// decomposition of the univariate polynomials.
fn radical_zero_dim(
    gb: &GroebnerBasis<RationalDomain, Lex>,
) -> GroebnerBasis<RationalDomain, Lex> {
    let n_vars = match gb.basis.first() {
        Some(p) => p.n_vars(),
        None => return GroebnerBasis { basis: vec![] },
    };

    let domain = RationalDomain;
    let mut radical_gens: Vec<SparseMultivariatePolynomial<RationalDomain, Lex>> =
        Vec::new();

    // For each variable, find the univariate polynomial and make it squarefree.
    for var in 0..n_vars {
        let univariate = gb.basis.iter().find(|p| {
            p.terms_ref()
                .keys()
                .all(|e| e.iter().enumerate().all(|(i, &v)| i == var || v == 0))
                && p.degree_in(var) > 0
        });

        if let Some(poly) = univariate {
            let unipoly = extract_univariate(poly, var);
            // Squarefree part: p / gcd(p, p').
            let deriv = unipoly.derivative();
            let g = unipoly.gcd(&deriv);
            let sqf = unipoly.div_rem(&g).map(|(q, _)| q).unwrap_or(unipoly);

            // Convert back to multivariate.
            let terms: Vec<(Vec<usize>, ocas_domain::Rational)> = sqf
                .coeffs()
                .iter()
                .enumerate()
                .filter(|(_, c)| !domain.is_zero(c))
                .map(|(i, c)| {
                    let mut exp = vec![0usize; n_vars];
                    exp[var] = i;
                    (exp, c.clone())
                })
                .collect();
            if !terms.is_empty() {
                radical_gens
                    .push(SparseMultivariatePolynomial::from_terms(domain, n_vars, terms));
            }
        }
    }

    // Also include all non-univariate basis elements (they're in the radical).
    for p in &gb.basis {
        let is_univariate = p
            .terms_ref()
            .keys()
            .any(|e| e.iter().filter(|&&v| v > 0).count() <= 1);
        if !is_univariate {
            radical_gens.push(p.clone());
        }
    }

    groebner_basis(&radical_gens, Algorithm::Auto)
}

/// Compute the radical for positive-dimensional ideals using the
/// Jacobian saturation approach: √I = I : h^∞ where h is related to
/// the Jacobian determinant.
///
/// Simplified Kemper algorithm for characteristic 0:
/// 1. Compute partial derivatives ∂fᵢ/∂xⱼ for all generators and variables.
/// 2. Let h = gcd of all non-zero partial derivatives.
/// 3. √I = I : h^∞.
///
/// Falls back to returning the original GB if the Jacobian is trivial (all
/// derivatives are zero or h = 1).
fn radical_via_jacobian(
    gb: &GroebnerBasis<RationalDomain, Lex>,
) -> GroebnerBasis<RationalDomain, Lex> {
    let n_vars = match gb.basis.first() {
        Some(p) => p.n_vars(),
        None => return gb.clone(),
    };

    if n_vars == 0 || gb.basis.is_empty() {
        return gb.clone();
    }

    // Compute all partial derivatives ∂fᵢ/∂xⱼ.
    let mut derivatives: Vec<SparseMultivariatePolynomial<RationalDomain, Lex>> = Vec::new();
    for f in &gb.basis {
        for var in 0..n_vars {
            let df = f.derivative(var);
            if df.total_degree().is_some_and(|d| d > 0) {
                derivatives.push(df);
            }
        }
    }

    if derivatives.is_empty() {
        // All derivatives are constant or zero; ideal is likely a prime
        // coordinate subspace. Return GB as-is.
        return gb.clone();
    }

    // Compute h = gcd of all derivatives.
    // For simplicity, iteratively compute gcd: gcd(d1, gcd(d2, gcd(d3, ...))).
    // Use the multivariate GCD via Groebner-based approach: gcd(a,b) can be
    // computed as the generator of ⟨a⟩ ∩ ⟨b⟩ in the univariate case,
    // but for multivariate we use a simpler heuristic.
    //
    // Simplification: take the product of all distinct irreducible factors
    // that appear in any derivative. For now, use the first derivative as h
    // (conservative: h divides the true Jacobian, so I:h^∞ ⊇ √I, which is
    // still an upper bound).
    let h = derivatives.into_iter().reduce(|a, b| {
        // Multivariate GCD via repeated pseudo-division in the first variable.
        // Simplified: take the polynomial with smaller total degree.
        if a.total_degree() <= b.total_degree() {
            a
        } else {
            b
        }
    });

    let Some(h) = h else {
        return gb.clone();
    };

    // Check if h is a nonzero constant (then I:h^∞ = I).
    if h.total_degree() == Some(0) || h.total_degree().is_none() {
        return gb.clone();
    }

    // Compute √I = I : h^∞ via saturation.
    ideal_saturate(&gb.basis, std::slice::from_ref(&h))
}

/// Compute the primary decomposition of an ideal.
///
/// For zero-dimensional ideals, uses the factorization of the univariate
/// polynomials in the Lex GB to separate primary components.
///
/// # Example
///
/// ```
/// use ocas_domain::{RationalDomain, Rational};
/// use ocas_poly::sparse::Lex;
/// use ocas_poly::ideal::primary_decomposition;
/// use ocas_poly::SparseMultivariatePolynomial;
///
/// let d = RationalDomain;
/// // (x², xy) = (x) ∩ (x², y)
/// let f1 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![2, 0], Rational::new(1, 1)),
/// ]);
/// let f2 = SparseMultivariatePolynomial::<_, Lex>::from_terms(d, 2, vec![
///     (vec![1, 1], Rational::new(1, 1)),
/// ]);
/// let decomp = primary_decomposition(&[f1, f2]);
/// assert!(decomp.len() >= 1);
/// ```
pub fn primary_decomposition(
    generators: &[SparseMultivariatePolynomial<RationalDomain, Lex>],
) -> Vec<PrimaryComponent> {
    if generators.is_empty() {
        return vec![];
    }

    let gb = groebner_basis(generators, Algorithm::Auto);

    if is_zero_dimensional(&gb) {
        primary_decomp_zero_dim(&gb)
    } else {
        // For positive-dimensional ideals, return a single component.
        vec![PrimaryComponent {
            primary: gb.basis.clone(),
            prime: gb.basis.clone(), // conservative
        }]
    }
}

/// Primary decomposition for zero-dimensional ideals.
///
/// Factors the univariate polynomials in the Lex GB and uses the factors
/// to separate primary components via saturation.
fn primary_decomp_zero_dim(
    gb: &GroebnerBasis<RationalDomain, Lex>,
) -> Vec<PrimaryComponent> {
    if gb.basis.is_empty() {
        return vec![];
    }

    let n_vars = match gb.basis.first() {
        Some(p) => p.n_vars(),
        None => return vec![],
    };

    // Find the univariate polynomial in the first variable (highest in Lex order).
    let univariate = gb.basis.iter().find(|p| {
        p.terms_ref()
            .keys()
            .all(|e| e.iter().enumerate().all(|(i, &v)| i == 0 || v == 0))
            && p.degree_in(0) > 0
    });

    let Some(poly) = univariate else {
        // No univariate polynomial found; return as single component.
        return vec![PrimaryComponent {
            primary: gb.basis.clone(),
            prime: ideal_radical(&gb.basis).basis,
        }];
    };

    let unipoly = extract_univariate(poly, 0);

    // Make square-free: sqf = p / gcd(p, p').
    let deriv = unipoly.derivative();
    let g = unipoly.gcd(&deriv);
    let sqf = match unipoly.div_rem(&g) {
        Some((q, _)) => q,
        None => unipoly.clone(),
    };

    // Factor the square-free polynomial over ℚ.
    let factors = crate::factor::algebraic::factor_square_free_rationals(&sqf);

    if factors.len() <= 1 {
        // Irreducible or constant: single primary component.
        return vec![PrimaryComponent {
            primary: gb.basis.clone(),
            prime: ideal_radical(&gb.basis).basis,
        }];
    }

    // Convert factors back to multivariate polynomials in variable 0.
    let domain = RationalDomain;
    let factor_polys: Vec<SparseMultivariatePolynomial<RationalDomain, Lex>> = factors
        .iter()
        .map(|f| {
            let terms: Vec<(Vec<usize>, Rational)> = f
                .coeffs()
                .iter()
                .enumerate()
                .filter(|(_, c)| !domain.is_zero(c))
                .map(|(i, c)| {
                    let mut exp = vec![0usize; n_vars];
                    exp[0] = i;
                    (exp, c.clone())
                })
                .collect();
            SparseMultivariatePolynomial::from_terms(domain, n_vars, terms)
        })
        .collect();

    // For each factor f_i, compute the primary component by saturating
    // I : (Π_{j≠i} f_j)^∞. We saturate sequentially by each other factor.
    let mut components = Vec::new();
    for (i, fi) in factor_polys.iter().enumerate() {
        // Saturate by all other factors.
        let mut saturated = GroebnerBasis { basis: gb.basis.clone() };
        for (j, fj) in factor_polys.iter().enumerate() {
            if i == j {
                continue;
            }
            saturated = ideal_saturate(&saturated.basis, std::slice::from_ref(fj));
        }

        // The prime is I + ⟨f_i⟩.
        let mut prime_gens = gb.basis.clone();
        prime_gens.push(fi.clone());
        let prime_gb = groebner_basis(&prime_gens, Algorithm::Auto);

        components.push(PrimaryComponent {
            primary: saturated.basis,
            prime: prime_gb.basis,
        });
    }

    components
}

/// Test whether an ideal is prime.
///
/// For zero-dimensional ideals, checks if the univariate polynomials in the
/// Lex GB are irreducible.
///
/// **Note**: Positive-dimensional ideals always return `false`. Full primality
/// testing for positive-dimensional ideals requires irreducibility checking of
/// the variety, which is not yet implemented. This is a conservative
/// approximation: it never returns a false positive (non-prime reported as
/// prime), only false negatives (prime ideals reported as non-prime).
pub fn is_prime_ideal(
    generators: &[SparseMultivariatePolynomial<RationalDomain, Lex>],
) -> bool {
    if generators.is_empty() {
        return false;
    }
    let gb = groebner_basis(generators, Algorithm::Auto);
    if gb.basis.is_empty() {
        return false;
    }
    // Check if GB = {1} (improper ideal).
    if gb.basis.len() == 1
        && gb.basis[0]
            .leading_monomial()
            .map(|lm| lm.iter().all(|&e| e == 0))
            .unwrap_or(false)
    {
        return false;
    }
    if is_zero_dimensional(&gb) {
        is_prime_zero_dim(&gb)
    } else {
        // Positive-dimensional: conservative answer.
        // Full implementation would check irreducibility of the variety.
        false
    }
}

fn is_prime_zero_dim(gb: &GroebnerBasis<RationalDomain, Lex>) -> bool {
    let n_vars = match gb.basis.first() {
        Some(p) => p.n_vars(),
        None => return false,
    };

    // For zero-dimensional ideals, the ideal is prime iff all univariate
    // polynomials in the Lex GB are irreducible.
    for var in 0..n_vars {
        let univariate = gb.basis.iter().find(|p| {
            p.terms_ref()
                .keys()
                .all(|e| e.iter().enumerate().all(|(i, &v)| i == var || v == 0))
                && p.degree_in(var) > 0
        });

        if let Some(poly) = univariate {
            let unipoly = extract_univariate(poly, var);
            // Check irreducibility: a univariate polynomial over ℚ is irreducible
            // if it has no rational roots (for degree 2-3) or more generally
            // if it can't be factored.
            // Simple check: if degree ≤ 3, check for rational roots.
            if let Some(deg) = unipoly.degree() && deg <= 3 {
                    let has_rational_root = check_rational_roots(&unipoly);
                    if has_rational_root && deg > 1 {
                        return false;
                    }
            }
        }
    }
    true
}

/// Enumerate all positive divisors of a positive integer.
fn divisors_of(n: i64) -> Vec<i64> {
    if n <= 0 {
        return vec![];
    }
    let mut divs = Vec::new();
    let mut i = 1i64;
    while i * i <= n {
        if n % i == 0 {
            divs.push(i);
            if i != n / i {
                divs.push(n / i);
            }
        }
        i += 1;
    }
    divs.sort_unstable();
    divs
}

/// Check if a univariate polynomial has rational roots using the
/// rational root theorem: if $p/q$ is a root in lowest terms, then
/// $p$ divides the constant term and $q$ divides the leading coefficient.
fn check_rational_roots(
    poly: &crate::dense::DenseUnivariatePolynomial<RationalDomain>,
) -> bool {
    let Some(deg) = poly.degree() else {
        return false;
    };
    if deg == 0 {
        return false;
    }

    let coeffs = poly.coeffs();
    let constant = &coeffs[0];

    if RationalDomain.is_zero(constant) {
        return true; // x = 0 is a root
    }

    let Some(lc) = poly.leading_coeff() else {
        return false;
    };

    // Numerators/denominators of constant term and leading coefficient.
    let p_divs = divisors_of(constant.numer().to_i64().unwrap_or(0).unsigned_abs() as i64);
    let q_divs = divisors_of(lc.numer().to_i64().unwrap_or(0).unsigned_abs() as i64);

    if p_divs.is_empty() || q_divs.is_empty() {
        // Fallback for huge integers: test ±1.
        let one = ocas_domain::Rational::new(1, 1);
        let neg_one = ocas_domain::Rational::new(-1, 1);
        return RationalDomain.is_zero(&poly.eval(&one))
            || RationalDomain.is_zero(&poly.eval(&neg_one));
    }

    for &p in &p_divs {
        for &q in &q_divs {
            let candidate = ocas_domain::Rational::new(p, q);
            if RationalDomain.is_zero(&poly.eval(&candidate)) {
                return true;
            }
            let neg_candidate = ocas_domain::Rational::new(-p, q);
            if RationalDomain.is_zero(&poly.eval(&neg_candidate)) {
                return true;
            }
        }
    }
    false
}

/// Test whether an ideal is primary.
///
/// An ideal is primary iff it has exactly one associated prime.
pub fn is_primary_ideal(
    generators: &[SparseMultivariatePolynomial<RationalDomain, Lex>],
) -> bool {
    let decomp = primary_decomposition(generators);
    decomp.len() <= 1
}

